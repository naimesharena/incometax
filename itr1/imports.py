# order matters: the first category whose keyword appears in the context wins;
# specific income families are tested before the generic tax-credit buckets so
# that e.g. a company named "TCS Ltd" cannot misfile a dividend as TCS.
_AIS_CATEGORIES = [
    ("tds_salary", ("tds on salary", "salary-tds", "tds u/s 192", "192")),
    ("interest_savings", ("interest from savings", "savings bank interest")),
    ("interest_deposit", ("interest from deposit", "interest from fixed deposit",
                          "term deposit interest")),
    ("dividend", ("dividend",)),
    ("rent", ("rent received", "rental income")),
    ("salary", ("salary", "sft-012 employer", "sft-013")),
    ("tcs", ("tax collected", "tcs amount", "tcs u/s", "206c")),
    ("tds_other", ("tax deducted", "tds", "194")),
    ("advance_tax", ("advance tax", "self assessment", "self-assessment",
                     "payment of taxes", "tax payment", "self assessment tax")),
    ("mf_sale", ("mutual fund units", "sale of securities", "purchase of securities",
                 "units of mutual fund")),
    ("property_txn", ("immovable property", "transfer of immovable")),
    ("foreign", ("foreign remittance", "forex")),
    ("cash", ("cash deposit", "cash withdrawal", "cash payment")),
    ("turnover", ("turnover", "business receipts", "gross receipts")),
    ("other", ("",)),
]


def _classify(text: str):
    t = text.lower()
    for cat, keys in _AIS_CATEGORIES:
        if any(k and k in t for k in keys):
            return cat
    return "other"


def parse_ais_json(doc) -> dict:
    """Generic walker over any AIS JSON layout; buckets records by context."""
    entries: list[dict] = []
    ay = str(doc.get("assessmentYear") or doc.get("AssessmentYear")
             or doc.get("AY") or "") if isinstance(doc, dict) else ""

    def visit(node, ctx: list[str]):
        if isinstance(node, dict):
            amount_keys = [k for k in node
                           if k.lower() in ("amount", "transactionamount", "paidamount",
                                            "grossamount", "tdsamount", "tcsamount",
                                            "taxdeducted", "taxcollected") and
                           isinstance(node[k], (int, float, str))]
            if amount_keys and not any(isinstance(v, (list, dict)) for v in node.values()):
                amt = 0.0
                for k in amount_keys:
                    try:
                        amt = float(str(node[k]).replace(",", "") or 0)
                        break
                    except ValueError:
                        continue
                desc = " / ".join(str(node.get(k, "")) for k in
                                  ("informationDescription", "description",
                                   "informationSource", "sourceDescription",
                                   "name", "deductorName") if node.get(k))
                context = " > ".join(ctx + [desc])
                entries.append({
                    "category": _classify(context),
                    "description": desc or ctx[-1] if ctx else desc or "AIS entry",
                    "context": context,
                    "amount": amt,
                    "date": str(node.get("transactionDate") or node.get("informationDate")
                                or node.get("date") or ""),
                    "fields": {k: v for k, v in node.items()
                               if not isinstance(v, (list, dict))},
                })
            for k, v in node.items():
                visit(v, ctx + [str(k)])
        elif isinstance(node, list):
            for item in node:
                visit(item, ctx)

    if isinstance(doc, dict):
        visit(doc, [])
    return {"assessment_year": ay, "entries": entries}


def _read_zip(passwords: list[str], blob: bytes) -> bytes:
    zf = zipfile.ZipFile(io.BytesIO(blob))
    json_names = [n for n in zf.namelist() if n.lower().endswith(".json")]
    names = json_names or zf.namelist()
    if not names:
        raise DataError("The ZIP archive is empty.", field="AIS file")
    last_err: Exception | None = None
    for pwd in passwords:
        try:
            return zf.read(names[0], pwd=pwd.encode())
        except RuntimeError as exc:          # bad password
            last_err = exc
            continue
    raise DataError("Could not unlock the AIS ZIP — password did not match. "
                    "It is usually your PAN (lower case) followed by date of birth "
                    "in DDMMYYYY, e.g. abcd1234a01011990.",
                    field="AIS password") from last_err


def parse_ais(blob: bytes, filename: str, data: dict) -> dict:
    """Parse AIS from raw JSON text or the portal's password ZIP."""
    name = (filename or "").lower()
    if name.endswith(".zip") or blob[:2] == b"PK":
        pwds = passwords_for(data, "ais")
        if not pwds:
            raise DataError("Fill your PAN and date of birth first — they form the "
                            "AIS file password.", field="AIS password")
        blob = _read_zip(pwds, blob)
    try:
        doc = json.loads(blob.decode("utf-8", "replace"))
    except ValueError as exc:
        raise DataError("The AIS content is not valid JSON — upload the JSON or "
                        "the ZIP exactly as downloaded.", field="AIS file") from exc
    out = parse_ais_json(doc)
    out["password_used"] = bool(name.endswith(".zip") or blob[:2] == b"PK")
    return out


