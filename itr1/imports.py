_AIS_INCOME_MAP = {
    "interest_savings": {"nature": "SAV", "label": "Savings bank interest (AIS)"},
    "interest_deposit": {"nature": "IFD", "label": "Interest on deposits (AIS)"},
    "dividend": {"nature": "DIV", "label": "Dividend (AIS)"},
    "other": {"nature": "OTH", "label": "Other income (AIS)"},
}


def ais_income_candidates(ais: dict) -> list[dict]:
    """Income entries from AIS that can be pushed into the return with one tap."""
    out = []
    for i, e in enumerate(ais.get("entries", [])):
        cat = e["category"]
        if cat in _AIS_INCOME_MAP and e["amount"] > 0:
            m = _AIS_INCOME_MAP[cat]
            out.append({
                "id": i, "category": cat, "amount": int(round(e["amount"])),
                "description": e["description"], "date": e["date"],
                "target": {"list": "other_sources",
                           "row": {"nature": m["nature"], "amount": int(round(e["amount"])),
                                   "description": f'{m["label"]}: {e["description"]}'}},
            })
        elif cat == "salary" and e["amount"] > 0:
            out.append({
                "id": i, "category": "salary", "amount": int(round(e["amount"])),
                "description": e["description"], "date": e["date"],
                "target": {"list": "salary_box", "row": {"salary_17_1": int(round(e["amount"]))}},
            })
    return out


def apply_ais_items(data: dict, candidates: list[dict], ids: list[int]) -> tuple[dict, list[str]]:
    """Add the chosen AIS incomes into the working data (tap-to-add)."""
    import copy
    out = copy.deepcopy(data)
    notes: list[str] = []
    want = set(ids)
    for c in candidates:
        if c["id"] not in want:
            continue
        t = c["target"]
        if t["list"] == "other_sources":
            rows = out.setdefault("other_sources", [])
            dup = any(r.get("nature") == t["row"]["nature"]
                      and int(r.get("amount") or 0) == t["row"]["amount"]
                      and t["row"]["description"][:20] in str(r.get("description", ""))
                      for r in rows)
            if not dup:
                rows.append(dict(t["row"]))
                notes.append(f"Added {t['row']['description']} — Rs. {c['amount']:,}.")
        elif t["list"] == "salary_box":
            sal = out.setdefault("salary", {})
            existing = int(sal.get("salary_17_1") or 0)
            if existing == t["row"]["salary_17_1"]:
                continue
            if existing:
                sal["salary_17_1"] = max(existing, t["row"]["salary_17_1"])
                notes.append("Salary box updated to the AIS figure (higher of "
                             "existing/AIS kept).")
            else:
                sal["salary_17_1"] = t["row"]["salary_17_1"]
                notes.append(f"Salary of Rs. {c['amount']:,} added from AIS.")
    if not notes:
        notes.append("Nothing new to add (already present or nothing selected).")
    return out, notes


def compare_with_ais(data: dict, ais: dict, computed: dict) -> list[dict]:
    """Side-by-side of AIS totals vs our computation, per income family.

    ``computed`` is the report dict of the current build (any ITR form).
    """
    totals: dict[str, float] = {}
    for e in ais.get("entries", []):
        totals[e["category"]] = totals.get(e["category"], 0.0) + e["amount"]

    os_rows = data.get("other_sources") or []

    def os_amount(*natures):
        return sum(int(r.get("amount") or 0) for r in os_rows
                   if str(r.get("nature")) in natures)

    sal = (data.get("salary") or {})
    try:
        salary_box = float(sal.get("salary_17_1") or 0)
    except (TypeError, ValueError):
        salary_box = 0
    if not salary_box:
        salary_box = sum(float(c.get("amount") or 0)
                         for c in sal.get("components") or [])

    hp = 0.0
    for p in data.get("house_properties") or []:
        try:
            hp += float(p.get("annual_lettable_value") or 0)
        except (TypeError, ValueError):
            continue

    mapping = [
        ("Salary", "salary", salary_box),
        ("Interest (savings + deposits)", "interest",
         os_amount("SAV", "IFD", "INT", "TAX")),
        ("Dividend", "dividend", os_amount("DIV")),
        ("Rent received", "rent", hp),
    ]
    rows = []
    for label, cat, ours in mapping:
        ais_amt = (totals.get(cat, 0.0)
                   + (totals.get("interest_savings", 0.0)
                      + totals.get("interest_deposit", 0.0) if cat == "interest" else 0.0))
        ais_amt = int(round(ais_amt))
        ours = int(round(ours))
        if not ais_amt and not ours:
            continue
        diff = ours - ais_amt
        if ais_amt == ours:
            status = "matched"
        elif ours > ais_amt:
            status = "return higher" if ais_amt else "missing in AIS"
        else:
            status = "AIS higher — review" if ours else "missing in return"
        rows.append({"head": label, "ais": ais_amt, "return": ours,
                     "difference": diff, "status": status})
    return rows
