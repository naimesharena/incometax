def _walk(node, path=""):
    if isinstance(node, dict):
        for k, v in node.items():
            yield path + "/" + k, v
            yield from _walk(v, path + "/" + k)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            yield from _walk(v, f"{path}[{i}]")


def _first_int(doc, *key_names, default=0):
    """First integer-ish value whose key matches any of the names (exactly)."""
    wanted = {k.lower() for k in key_names}
    for _path, v in _walk(doc):
        key = _path.rsplit("/", 1)[-1]
        key = re.sub(r"\[\d+\]$", "", key).lower()
        if key in wanted:
            try:
                return int(float(v))
            except (TypeError, ValueError):
                continue
    return default


def _first_str(doc, *key_names, default=""):
    wanted = {k.lower() for k in key_names}
    for _path, v in _walk(doc):
        key = re.sub(r"\[\d+\]$", "", _path.rsplit("/", 1)[-1]).lower()
        if key in wanted and isinstance(v, str) and v.strip():
            return v.strip()
    return default


def _get_path(doc, *names):
    """Exact key-path getter through nested dicts."""
    cur = doc
    for n in names:
        if not isinstance(cur, dict) or n not in cur:
            return None
        cur = cur[n]
    return cur


def parse_itr_json(payload) -> dict:
    """Parse any ITR JSON (our app / the portal's prefilled download).

    Returns a normalized ``summary`` used for prefill, YoY comparison and
    loss carry-forward capture.
    """
    try:
        doc = json.loads(payload) if isinstance(payload, (str, bytes)) else payload
    except (ValueError, TypeError) as exc:
        raise DataError(f"The selected file is not valid JSON ({exc}).",
                        field="ITR JSON file") from exc
    if not isinstance(doc, dict) or "ITR" not in doc:
        raise DataError("This JSON does not look like an ITR document "
                        "(missing the top-level 'ITR' object).",
                        field="ITR JSON file")
    forms = [k for k in doc["ITR"] if isinstance(doc["ITR"][k], dict)]
    form = forms[0] if forms else ""
    body = doc["ITR"].get(form, {}) if form else {}

    ay = _first_str(doc, "AssessmentYear")
    name_parts = [
        _first_str(doc, "FirstName"), _first_str(doc, "MiddleName"),
        _first_str(doc, "SurNameOrOrgName"),
    ]
    heads = {}
    if form in ("ITR1", "ITR4"):
        inc = body.get("ITR1_IncomeDeductions") or body.get("IncomeDeductions") or {}
        heads = {
            "business": inc.get("IncomeFromBusinessProf", 0),
            "salary": inc.get("IncomeFromSal", 0),
            "hp": inc.get("TotalIncomeChargeableUnHP", 0),
            "os": inc.get("IncomeOthSrc", 0)
            if isinstance(inc.get("IncomeOthSrc"), int) else 0,
            "ltcg112a": _first_int(inc, "LongCap112A"),
            "gti": inc.get("GrossTotIncomeIncLTCG112A", 0),
            "total_income": inc.get("TotalIncome", 0),
        }
    elif form == "ITR2":
        pbti = body.get("PartB-TI") or {}
        capg = pbti.get("CapGain") or {}
        heads = {
            "salary": pbti.get("Salaries", 0),
            "hp": pbti.get("IncomeFromHP", 0),
            "stcg": (capg.get("ShortTerm") or {}).get("TotalShortTerm", 0),
            "ltcg": (capg.get("LongTerm") or {}).get("TotalLongTerm", 0),
            "cg": capg.get("TotalCapGains", 0),
            "os": (pbti.get("IncFromOS") or {}).get("TotIncFromOS", 0),
            "gti": pbti.get("GrossTotalIncome", 0),
            "total_income": pbti.get("TotalIncome", 0),
            "losses_cf_declared": pbti.get("LossesOfCurrentYearCarriedFwd", 0),
        }
    elif form == "ITR3":
        pbti = body.get("PartB-TI") or {}
        heads = {
            "business": _first_int(pbti, "ProfIncGainsBus"),
            "salary": pbti.get("Salaries", 0),
            "hp": pbti.get("IncomeFromHP", 0),
            "cg": (pbti.get("CapGain") or {}).get("TotalCapGains", 0),
            "os": (pbti.get("IncFromOS") or {}).get("TotIncFromOS", 0),
            "gti": pbti.get("GrossTotalIncome", 0),
            "total_income": pbti.get("TotalIncome", 0),
        }
    else:
        heads = {"total_income": _first_int(doc, "TotalIncome"),
                 "gti": _first_int(doc, "GrossTotalIncome")}

    # taxes
    tax = {
        "total_tax_plus_interest": _first_int(doc, "AggregateTaxInterestLiability",
                                              "TotTaxPlusIntrstPay"),
        "tds": _first_int(_get_path(body, "TaxPaid") or {}, "TDS")
        or _first_int(doc, "TDS"),
        "tcs": _first_int(doc, "TCS"),
        "advance_tax": _first_int(doc, "AdvanceTax"),
        "self_assessment": _first_int(doc, "SelfAssessmentTax"),
        "refund": _first_int(doc, "RefundDue"),
        "balance_payable": _first_int(doc, "BalTaxPayable"),
    }

    # losses carried forward (ScheduleCFL for the NEXT year / current-yr not
    # set off under BFLA in this return)
    losses = {"stcg_cf": 0, "ltcg_cf": 0, "hp_cf": 0, "business_cf": 0}
    cfl = _get_path(body, "ScheduleCFL")
    if isinstance(cfl, dict):
        losses["stcg_cf"] = _first_int(cfl, "TotalAmtSTCGCL", "InStcgCurYr")
        losses["ltcg_cf"] = _first_int(cfl, "TotalAmtLTCGCL", "InLtcgCurYr")
        losses["hp_cf"] = _first_int(cfl, "CurrYrHPossCF", "TotalBFLossesCFFwd")
    if not losses["stcg_cf"]:
        losses["stcg_cf"] = _first_int(doc, "TotalAmtSTCGCL")
    if not losses["ltcg_cf"]:
        losses["ltcg_cf"] = _first_int(doc, "TotalAmtLTCGCL")

    # ---- prefill payload (identity / contact / bank / verification) ----
    pi = _get_path(body, "PartA_GEN1", "PersonalInfo") or body.get("PersonalInfo") or {}
    addr = pi.get("Address") or {}
    prefill = {
        "personal": {
            "first_name": (pi.get("AssesseeName") or {}).get("FirstName", ""),
            "middle_name": (pi.get("AssesseeName") or {}).get("MiddleName", ""),
            "last_name": (pi.get("AssesseeName") or {}).get("SurNameOrOrgName", ""),
            "pan": pi.get("PAN", ""),
            "dob": pi.get("DOB", ""),
            "aadhaar": pi.get("AadhaarCardNo", ""),
            "employer_category": pi.get("EmployerCategory", ""),
            "address": {
                "residence_no": addr.get("ResidenceNo", ""),
                "residence_name": addr.get("ResidenceName", ""),
                "road_or_street": addr.get("RoadOrStreet", ""),
                "locality_or_area": addr.get("LocalityOrArea", ""),
                "city_or_town_or_district": addr.get("CityOrTownOrDistrict", ""),
                "state_code": addr.get("StateCode", ""),
                "country_code": addr.get("CountryCode", "91"),
                "pin_code": addr.get("PinCode", ""),
                "country_code_mobile": addr.get("CountryCodeMobile", 91),
                "mobile_no": addr.get("MobileNo", ""),
                "email_address": addr.get("EmailAddress", ""),
            },
        },
        "verification": {
            "name": " ".join(p for p in name_parts if p),
            "father_name": _first_str(doc, "FatherName"),
            "pan": pi.get("PAN", ""),
            "capacity": _first_str(doc, "Capacity", default="S"),
            "place": _first_str(doc, "Place"),
        },
        "bank_accounts": [],
    }
    for _p, v in _walk(doc):
        if _p.lower().endswith("addtnlbankdetails") and isinstance(v, list):
            for b in v:
                if isinstance(b, dict) and b.get("BankAccountNo"):
                    prefill["bank_accounts"].append({
                        "ifsc": b.get("IFSCCode", ""),
                        "bank_name": b.get("BankName", ""),
                        "account_no": str(b.get("BankAccountNo", "")),
                        "account_type": b.get("AccountType", "SB"),
                        "use_for_refund": str(b.get("UseForRefund", "false")) == "true",
                    })

    return {
        "form": form,
        "assessment_year": ay,
        "name": " ".join(p for p in name_parts if p),
        "pan": pi.get("PAN", "") or _first_str(doc, "PAN"),
        "regime": ("old" if _first_str(doc, "OptOutNewTaxRegime") == "Y"
                   or _first_str(doc, "Form10IEAEarlierAYOldRegime") == "Y" else "new"),
        "heads": heads,
        "tax": tax,
        "losses": losses,
        "prefill": prefill,
        "bank_count": len(prefill["bank_accounts"]),
    }


def apply_itr_prefill(data: dict, summary: dict, sections: list[str] | None = None) -> dict:
    """Merge a parsed previous-year ITR JSON into the working data.

    sections: subset of {"personal", "bank", "verification"} — identity and
    bank are the useful, year-invariant parts.  Returns (data, notes).
    """
    import copy
    out = copy.deepcopy(data)
    notes: list[str] = []
    pre = summary.get("prefill") or {}
    wanted = set(sections or ("personal", "bank", "verification"))

    if "personal" in wanted and (pre.get("personal") or {}).get("pan"):
        old = out.get("personal") or {}
        incoming = pre["personal"]
        merged = dict(old)
        for k, v in incoming.items():
            if k == "address":
                continue
            if v and not old.get(k):
                merged[k] = v
        addr_old = old.get("address") or {}
        addr_new = dict(addr_old)
        for k, v in (incoming.get("address") or {}).items():
            if v not in ("", None) and not addr_old.get(k):
                addr_new[k] = v
        merged["address"] = addr_new
        out["personal"] = merged
        notes.append("Identity & contact details filled from the previous-year JSON "
                     "(only empty fields were touched).")
    if "bank" in wanted and pre.get("bank_accounts") and not out.get("bank_accounts"):
        out["bank_accounts"] = pre["bank_accounts"]
        notes.append(f"{len(pre['bank_accounts'])} bank account(s) imported.")
    if "verification" in wanted:
        ver_old = out.get("verification") or {}
        ver_new = dict(ver_old)
        for k, v in (pre.get("verification") or {}).items():
            if v and not ver_old.get(k):
                ver_new[k] = v
        out["verification"] = ver_new

    losses = summary.get("losses") or {}
    if any(losses.get(k) for k in ("stcg_cf", "ltcg_cf", "hp_cf", "business_cf")):
        out.setdefault("losses_cf", {})
        for k in ("stcg_cf", "ltcg_cf", "hp_cf", "business_cf"):
            if losses.get(k) and not out["losses_cf"].get(k):
                out["losses_cf"][k] = losses[k]
        notes.append("Losses carried forward captured — review the 'Losses' panel; "
                     "this return shows them in CYLA/BFLA notes (auto set-off of "
                     "b/f losses is flagged for your confirmation).")
    return out, notes


