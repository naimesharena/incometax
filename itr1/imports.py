def year_on_year(cur_heads: dict, prev_summary: dict) -> list[dict]:
    """Compare current computation heads against the previous-year summary."""
    labels = {
        "salary": "Salary income (u/s 16)", "hp": "House property",
        "business": "Business / profession (presumptive)", "os": "Other sources",
        "ltcg112a": "LTCG u/s 112A", "stcg": "STCG (all rates)",
        "ltcg": "LTCG (all rates)", "cg": "Capital gains (total)",
        "gti": "Gross total income", "total_income": "Total income",
    }
    rows = []
    prev = prev_summary.get("heads") or {}
    for key, label in labels.items():
        cur = int(cur_heads.get(key, 0) or 0)
        old = int(prev.get(key, 0) or 0)
        if not cur and not old:
            continue
        delta = cur - old
        pct = round((delta / old) * 100, 1) if old else None
        rows.append({"head": label, "current": cur, "previous": old,
                     "delta": delta, "delta_pct": pct,
                     "trend": "up" if delta > 0 else "down" if delta < 0 else "same"})
    return rows


