def _dob_digits(dob: str) -> str:
    """YYYY-MM-DD -> DDMMYYYY."""
    dob = str(dob or "").strip()
    m = re.match(r"^((?:19|20)\d{2})-(\d{2})-(\d{2})$", dob)
    if m:
        return f"{m.group(3)}{m.group(2)}{m.group(1)}"
    digits = re.sub(r"\D", "", dob)
    return digits if len(digits) == 8 else ""


def passwords_for(data: dict, kind: str) -> list[str]:
    """Candidate passwords, best first.

    kind="ais"   -> pan.lower()+DOB(DDMMYYYY), then PAN-as-typed+DOB
    kind="26as"  -> DOB(DDMMYYYY), then PAN(lower/upper)+DOB
    """
    personal = (data or {}).get("personal") or {}
    pan = str(personal.get("pan") or "").strip()
    dob = _dob_digits(personal.get("dob"))
    out: list[str] = []
    if kind == "26as":
        if dob:
            out.append(dob)
        if pan and dob:
            out.extend([pan.lower() + dob, pan.upper() + dob])
    else:  # ais zip
        if pan and dob:
            out.extend([pan.lower() + dob, pan.upper() + dob])
        if dob:
            out.append(dob)
    # de-duplicate, keep order
    seen = set()
    uniq = []
    for p in out:
        if p and p not in seen:
            uniq.append(p)
            seen.add(p)
    return uniq


