"""Import hub — parse documents downloaded from the income-tax portal and
fold them into the friendly data model.

Supports:

* **ITR JSON** (any AY, ITR-1/2/3/4 — e.g. the AY 2025-26 file downloaded
  from the e-filing portal or generated by this app): identity/details
  prefill, income-head totals for year-on-year comparison, losses carried
  forward capture.
* **AIS** (Annual Information Statement) as JSON, or the password-protected
  ZIP shipped by the portal.  ZIP password is auto-derived from the user
  profile: ``pan.lower() + DDMMYYYY`` (e.g. ``abcd1234a01011990``) with a few
  safe variants.
* **Form 26AS / Annual Tax Statement** as PDF (password = date of birth,
  ``DDMMYYYY``) or plain text: TDS (salary / non-salary / 26QC), TCS and
  advance/self-assessment challans.

All parsers are tolerant: unknown sections are reported, never fatal.
"""

