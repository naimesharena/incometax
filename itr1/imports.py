def apply_26as(data: dict, parsed: dict, kinds: list[str] | None = None) -> tuple[dict, list[str]]:
    """Merge 26AS/AIS tax credits into ``data['tax_paid']``.

    kinds subsets: "tds_salary", "tds_others", "tds_rent", "tcs", "challans".
    Duplicates (same TAN+section+amount) are skipped.
    """
    import copy
    out = copy.deepcopy(data)
    tp = out.setdefault("tax_paid", {})
    notes: list[str] = []
    kinds = kinds or ["tds_salary", "tds_others", "tds_rent", "tcs", "challans"]

    def seen(rows, key):
        return {(str(r.get(key[0])), str(r.get(key[1])), int(r.get(key[2]) or 0))
                for r in rows}

    if "tds_salary" in kinds:
        rows = tp.setdefault("tds_on_salary", [])
        have = seen(rows, ("tan", "employer_name", "tds"))
        added = 0
        for r in parsed.get("tds_salary", []):
            sig = (r["tan"], r["name"], r["tax"])
            if sig in have or r["tax"] <= 0:
                continue
            rows.append({"tan": r["tan"], "employer_name": r["name"],
                         "salary_income": r.get("amount_paid", 0), "tds": r["tax"]})
            have.add(sig)
            added += 1
        if added:
            notes.append(f"{added} salary TDS row(s) added.")
    if "tds_others" in kinds:
        rows = tp.setdefault("tds_others", [])
        have = seen(rows, ("tan", "section", "tds_deducted"))
        added = 0
        for r in parsed.get("tds_others", []):
            sig = (r["tan"], r["section"], r["tax"])
            if sig in have or r["tax"] <= 0:
                continue
            rows.append({"tan": r["tan"], "deductor_name": r["name"],
                         "section": r["section"] or "94A",
                         "amount_paid": r.get("amount_paid", 0),
                         "tds_deducted": r["tax"], "tds_claimed": r["tax"]})
            have.add(sig)
            added += 1
        if added:
            notes.append(f"{added} non-salary TDS row(s) added.")
    if "tds_rent" in kinds:
        rows = tp.setdefault("tds3", [])
        added = 0
        for r in parsed.get("tds_rent", []):
            if r["tax"] <= 0:
                continue
            rows.append({"tenant_pan": "", "tenant_name": r["name"],
                         "gross_receipt": r.get("amount_paid", 0),
                         "tds_deducted": r["tax"], "tds_claimed": r["tax"]})
            added += 1
        if added:
            notes.append(f"{added} TDS-on-rent (26QC) row(s) added.")
    if "tcs" in kinds:
        rows = tp.setdefault("tcs", [])
        have = seen(rows, ("tan", "collector_name", "tcs_collected"))
        added = 0
        for r in parsed.get("tcs", []):
            sig = (r["tan"], r["name"], r["tax"])
            if sig in have or r["tax"] <= 0:
                continue
            rows.append({"tan": r["tan"], "collector_name": r["name"],
                         "amount_subject": r.get("amount_paid", 0),
                         "tcs_collected": r["tax"], "tcs_claimed": r["tax"]})
            have.add(sig)
            added += 1
        if added:
            notes.append(f"{added} TCS row(s) added.")
    if "challans" in kinds:
        rows = tp.setdefault("challans", [])
        have = {(str(r.get("bsr_code")), str(r.get("date")), int(r.get("amount") or 0))
                for r in rows}
        added = 0
        for c in parsed.get("challans", []):
            sig = (c["bsr_code"], c.get("date", ""), c["amount"])
            if sig in have or c["amount"] <= 0:
                continue
            rows.append({"bsr_code": c["bsr_code"], "date": c.get("date", ""),
                         "challan_no": c.get("challan_no", 0), "amount": c["amount"]})
            have.add(sig)
            added += 1
        if added:
            notes.append(f"{added} advance/self-assessment challan(s) added.")
    return out, notes


