_TAN_RE = r"[A-Z]{4}[0-9]{5}[A-Z]"
_NUM = r"[\d,]+(?:\.\d{1,2})?"


def _num(txt: str) -> int:
    try:
        return int(round(float(str(txt).replace(",", ""))))
    except (ValueError, TypeError):
        return 0


def parse_26as_text(text: str) -> dict:
    """Parse the classic 26AS text layout (also the text extracted from PDFs)."""
    tds_salary, tds_other, tds_rent, tcs, challans, refunds = [], [], [], [], [], []
    section_ctx = ""
    for raw in text.splitlines():
        line = " ".join(raw.split())
        if not line:
            continue
        low = line.lower()
        if "part-a1" in low or "part a1" in low:
            section_ctx = "salary"
        elif "part-a2" in low or "part a2" in low:
            section_ctx = "other"
        elif "part-b" in low and "tcs" in low:
            section_ctx = "tcs"
        elif "part-c" in low or "advance tax" in low or "self assessment" in low:
            section_ctx = "challan"
        elif "refund" in low:
            section_ctx = "refund"

        tans = re.findall(_TAN_RE, line)
        nums = [_num(n) for n in re.findall(_NUM, line)]
        bsr = re.search(r"\b(0\d{6})\b", line)
        date_m = re.search(r"\b(\d{2}[-/][A-Za-z]{3}[-/]\d{4}|\d{4}-\d{2}-\d{2}|"
                           r"\d{2}[-/]\d{2}[-/]\d{4})\b", line)
        sec_m = re.search(r"\b(19[24][A-Z0-9-]*|206[A-Z0-9-]*)\b", line)

        if bsr and len(nums) >= 1 and date_m:
            challans.append({"bsr_code": bsr.group(1), "date": _norm_date(date_m.group(1)),
                             "challan_no": nums[1] if len(nums) > 1 else 0,
                             "amount": nums[-1]})
            continue
        if tans and len(nums) >= 2:
            sec = sec_m.group(1) if sec_m else ""
            name_m = re.split(_TAN_RE, line)[0].strip(" .,-")
            is_tcs = section_ctx == "tcs" or sec.startswith("206")
            row = {
                "tan": tans[0],
                "name": name_m[-60:] or ("Collector" if is_tcs else "Deductor"),
                "section": sec or ("194A" if not is_tcs else "206C"),
                "amount_paid": nums[-2] if len(nums) >= 3 else 0,
                "tax": nums[-1],
                "year": _infer_year(line),
            }
            if is_tcs:
                tcs.append(row)
            elif "rent" in low or sec in ("194-IB", "194IB"):
                tds_rent.append(row)
            elif section_ctx == "salary" or sec == "192":
                tds_salary.append(row)
            else:
                tds_other.append(row)
            continue
        if section_ctx == "refund" and nums and "refund" in low:
            refunds.append({"amount": nums[-1], "description": line[:120]})
    return {"tds_salary": tds_salary, "tds_others": tds_other, "tds_rent": tds_rent,
            "tcs": tcs, "challans": challans, "refunds": refunds}


def _norm_date(s: str) -> str:
    s = s.strip()
    m = re.match(r"(\d{2})[-/]([A-Za-z]{3})[-/](\d{4})", s)
    months = {"jan": "01", "feb": "02", "mar": "03", "apr": "04", "may": "05",
              "jun": "06", "jul": "07", "aug": "08", "sep": "09", "oct": "10",
              "nov": "11", "dec": "12"}
    if m:
        return f"{m.group(3)}-{months.get(m.group(2).lower(), '01')}-{m.group(1)}"
    m = re.match(r"(\d{2})[-/](\d{2})[-/](\d{4})", s)
    if m:
        return f"{m.group(3)}-{m.group(2)}-{m.group(1)}"
    return s


def _infer_year(line: str) -> int:
    m = re.search(r"\b(20[12]\d)\b", line)
    return int(m.group(1)) if m else 2025


def parse_26as(blob: bytes, filename: str, data: dict) -> dict:
    """Form 26AS from PDF (password = DOB) or text."""
    name = (filename or "").lower()
    text = ""
    used_password = ""
    if name.endswith(".pdf") or blob[:4] == b"%PDF":
        try:
            from pypdf import PdfReader
        except ImportError as exc:  # pragma: no cover
            raise DataError("PDF support is unavailable on this server.",
                            field="26AS file") from exc
        reader = PdfReader(io.BytesIO(blob))
        if reader.is_encrypted:
            pwds = passwords_for(data, "26as")
            if not pwds:
                raise DataError("Fill your date of birth first — the 26AS PDF "
                                "password is DOB in DDMMYYYY.", field="26AS password")
            ok = False
            for pwd in pwds:
                try:
                    if reader.decrypt(pwd):
                        used_password = pwd
                        ok = True
                        break
                except Exception:                       # noqa: BLE001
                    continue
            if not ok:
                raise DataError("Could not unlock the 26AS PDF — password should be "
                                "your date of birth in DDMMYYYY.",
                                field="26AS password")
        parts = []
        for page in reader.pages:
            parts.append(page.extract_text() or "")
        text = "\n".join(parts)
    else:
        text = blob.decode("utf-8", "replace")
    if len(text.strip()) < 20:
        raise DataError("No readable text found in the 26AS file.",
                        field="26AS file")
    out = parse_26as_text(text)
    out["password_used"] = bool(used_password)
    out["raw_lines"] = max(0, len(text.splitlines()) - 1)
    return out


