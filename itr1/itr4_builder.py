def compute_presumptive(data: dict) -> dict:
    """Compute presumptive income; returns input echo + computed numbers."""
    pre = data.get("presumptive") or {}
    warnings: list[str] = []

    # --- 44AD ---
    rows_44ad = []
    tot_turnover = tot_bank = tot_cash = tot_other = 0
    for i, r in enumerate(pre.get("44ad") or [], 1):
        with field_scope(f"44AD business {i} ({r.get('name') or 'business'})",
                         f"presumptive.44ad.{i - 1}"):
            turnover = _g(r, "gross_turnover")
            bank = _g(r, "turnover_bank")
            cash = _g(r, "turnover_cash")
            other = _g(r, "turnover_other")
            declared = _g(r, "income_declared")
        if bank + cash + other > turnover:
            warnings.append(f"44AD '{r.get('name')}': bank+cash+other receipts exceed "
                            "gross turnover; other mode adjusted to balance.")
            other = max(0, turnover - bank - cash)
        if turnover and not (bank + cash + other):
            other = turnover
        presumptive = round((bank + other) * RATE_44AD_DIGITAL + cash * RATE_44AD_CASH)
        income = max(declared, presumptive)
        if declared and declared < presumptive:
            warnings.append(f"44AD '{r.get('name')}': declared income Rs. {declared:,} is "
                            f"below presumptive Rs. {presumptive:,} — presumptive applied "
                            "(lower declaration needs books + audit u/s 44AB).")
        rows_44ad.append({
            "name": str(r.get("name") or f"Business {i}"),
            "code": _check_nob_code(r.get("code") or "09028", "44AD",
                                    BUSINESS_CODES_44AD,
                                    f"presumptive.44ad.{i - 1}.code"),
            "description": str(r.get("description") or ""),
            "gross_turnover": turnover, "turnover_bank": bank, "turnover_cash": cash,
            "turnover_other": other, "presumptive_income": presumptive,
            "income": income,
        })
        tot_turnover += turnover
        tot_bank += bank
        tot_cash += cash
        tot_other += other
    if tot_turnover > TURNOVER_CAP_44AD:
        warnings.append(f"44AD turnover Rs. {tot_turnover:,} exceeds the Rs. 3,00,00,000 "
                        "limit (Rs. 3 cr applies only if cash receipts ≤ 5%) — ITR-3 may "
                        "be required with audit.")
    inc_44ad = sum(r["income"] for r in rows_44ad)

    # --- 44ADA ---
    rows_44ada = []
    tot_receipts = 0
    for i, r in enumerate(pre.get("44ada") or [], 1):
        with field_scope(f"44ADA profession {i} ({r.get('name') or 'profession'})",
                         f"presumptive.44ada.{i - 1}"):
            receipts = _g(r, "gross_receipts")
            bank = _g(r, "receipts_bank")
            cash = _g(r, "receipts_cash")
            other = _g(r, "receipts_other")
            declared = _g(r, "income_declared")
        if bank + cash + other > receipts:
            warnings.append(f"44ADA '{r.get('name')}': receipt split exceeds gross "
                            "receipts; other mode adjusted.")
            other = max(0, receipts - bank - cash)
        if receipts and not (bank + cash + other):
            bank = receipts
        presumptive = round(receipts * RATE_44ADA)
        income = max(declared, presumptive)
        if declared and declared < presumptive:
            warnings.append(f"44ADA '{r.get('name')}': declared income below 50% of "
                            "receipts — presumptive applied (lower needs audit).")
        rows_44ada.append({
            "name": str(r.get("name") or f"Profession {i}"),
            "code": _check_nob_code(r.get("code") or "14001", "44ADA",
                                    PROFESSION_CODES_44ADA,
                                    f"presumptive.44ada.{i - 1}.code"),
            "description": str(r.get("description") or ""),
            "gross_receipts": receipts, "receipts_bank": bank, "receipts_cash": cash,
            "receipts_other": other, "presumptive_income": presumptive,
            "income": income,
        })
        tot_receipts += receipts
    if tot_receipts > RECEIPTS_CAP_44ADA:
        warnings.append(f"44ADA receipts Rs. {tot_receipts:,} exceed Rs. 75,00,000 — "
                        "ITR-3 required (audit applies).")
    inc_44ada = sum(r["income"] for r in rows_44ada)

    # --- 44AE ---
    ae_in = pre.get("44ae") or {}
    rows_44ae = []
    for i, v in enumerate(ae_in.get("vehicles") or [], 1):
        with field_scope(f"Goods carriage {i} ({v.get('reg_no') or 'vehicle'})",
                         f"presumptive.44ae.vehicles.{i - 1}"):
            months = min(12, max(1, _g(v, "months", 12)))
            tonnage = _g(v, "tonnage")
        heavy = bool(v.get("heavy")) or tonnage > HEAVY_TONNAGE
        if heavy:
            income = RATE_44AE_HEAVY_PER_TON * max(1, tonnage) * months
        else:
            income = RATE_44AE_LIGHT * months
        rows_44ae.append({
            "reg_no": str(v.get("reg_no") or ""),
            "owned": str(v.get("owned") or "OWN"),
            "tonnage": tonnage if heavy else 0,
            "months": months,
            "heavy": heavy,
            "income": income,
        })
    inc_44ae = sum(r["income"] for r in rows_44ae)

    total = inc_44ad + inc_44ada + inc_44ae
    return {
        "44ad_rows": rows_44ad, "44ada_rows": rows_44ada, "44ae_rows": rows_44ae,
        "44ad_income": inc_44ad, "44ada_income": inc_44ada, "44ae_income": inc_44ae,
        "total_income": total,
        "totals": {"44ad_turnover": tot_turnover, "44ad_bank": tot_bank,
                   "44ad_cash": tot_cash, "44ad_other": tot_other,
                   "44ada_receipts": tot_receipts},
        "warnings": warnings,
        "financials": pre.get("financials") or {},
    }


def _schedule_bp(pres: dict) -> dict | None:
    if not (pres["44ad_rows"] or pres["44ada_rows"] or pres["44ae_rows"]):
        return None
    t = pres["totals"]
    bp: dict = {}
    if pres["44ad_rows"]:
        bp["NatOfBus44AD"] = [
            {"NameOfBusiness": r["name"], "CodeAD": r["code"],
             **({"Description": r["description"]} if r["description"] else {})}
            for r in pres["44ad_rows"]]
        bp["PersumptiveInc44AD"] = {
            "GrsTotalTrnOver": t["44ad_turnover"],
            "GrsTrnOverBank": t["44ad_bank"],
            "GrsTotalTrnOverInCash": t["44ad_cash"],
            "GrsTrnOverAnyOthMode": t["44ad_other"],
            "PersumptiveInc44AD6Per": round((t["44ad_bank"] + t["44ad_other"])
                                            * RATE_44AD_DIGITAL),
            "PersumptiveInc44AD8Per": round(t["44ad_cash"] * RATE_44AD_CASH),
            "TotPersumptiveInc44AD": pres["44ad_income"],
        }
    if pres["44ada_rows"]:
        bp["NatOfBus44ADA"] = [
            {"NameOfBusiness": r["name"], "CodeADA": r["code"],
             **({"Description": r["description"]} if r["description"] else {})}
            for r in pres["44ada_rows"]]
        bp["PersumptiveInc44ADA"] = {
            "GrsReceipt": t["44ada_receipts"],
            "GrsTrnOverBank44ADA": sum(r["receipts_bank"] for r in pres["44ada_rows"]),
            "GrsTotalTrnOverInCash44ADA": sum(r["receipts_cash"] for r in pres["44ada_rows"]),
            "GrsTrnOverAnyOthMode44ADA": sum(r["receipts_other"] for r in pres["44ada_rows"]),
            "TotPersumptiveInc44ADA": pres["44ada_income"],
        }
    if pres["44ae_rows"]:
        bp["NatOfBus44AE"] = [{"NameOfBusiness": "Plying/hiring goods carriages",
                               "CodeAE": "11008"}]
        bp["GoodsDtlsUs44AE"] = [
            {"RegNumberGoodsCarriage": (r["reg_no"] or "-")[:11],
             "OwnedLeasedHiredFlag": r["owned"] if r["owned"] in
             ("OWN", "LEASE", "HIRED") else "OWN",
             "TonnageCapacity": r["tonnage"],
             "HoldingPeriod": r["months"],
             "PresumptiveIncome": max(7500, r["income"])}
            for r in pres["44ae_rows"]]
        bp["PersumptiveInc44AE"] = {
            "TotPersumInc44AE": pres["44ae_income"],
            "SalInterestByFirm": 0,
            "TotalPersumptiveInc": (pres["44ad_income"] + pres["44ada_income"]
                                    + pres["44ae_income"]),
            "IncChargeableUnderBus": (pres["44ad_income"] + pres["44ada_income"]
                                      + pres["44ae_income"]),
        }
    fin_map = {
        "partner_capital": "PartnerMemberOwnCapital", "secured_loans": "SecuredLoans",
        "unsecured_loans": "UnSecuredLoans", "advances": "Advances",
        "sundry_creditors": "SundryCreditors", "other_liabilities": "OthrCurrLiab",
        "total_capital_liabilities": "TotCapLiabilities",
        "fixed_assets": "FixedAssets", "investments": "Investments",
        "inventories": "Inventories", "sundry_debtors": "SundryDebtors",
        "bank_balance": "BalWithBanks", "cash_in_hand": "CashInHand",
        "loans_and_advances": "LoansAndAdvances", "other_assets": "OtherAssets",
        "total_assets": "TotalAssets",
    }
    fin_in = pres.get("financials") or {}
    fin = {}
    for k, out_key in fin_map.items():
        with field_scope("Financial particulars of business", "presumptive.financials"):
            val = _g(fin_in, k)
        if val:
            fin[out_key] = val
    if fin:
        bp["FinanclPartclrOfBusiness"] = fin
    return bp


