RATE_44AD_DIGITAL = 0.06
RATE_44AD_CASH = 0.08
RATE_44ADA = 0.50
RATE_44AE_LIGHT = 7500          # per vehicle per month
RATE_44AE_HEAVY_PER_TON = 1000  # per ton per month (>12 MT)
HEAVY_TONNAGE = 12
TURNOVER_CAP_44AD = 30000000    # ₹3 crore
RECEIPTS_CAP_44ADA = 7500000    # ₹75 lakh

