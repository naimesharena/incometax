def _check_nob_code(code: str, scope: str, catalog: dict, field: str) -> str:
    """Validate a presumptive nature-of-business code like the official
    utility does (dropdown = its hidden master list)."""
    code = str(code or "")
    if code in catalog:
        return code
    raise DataError(
        f"{field}: nature-of-business code {code!r} is not in the official "
        f"{scope} dropdown ({len(catalog)} codes shipped in the CBDT "
        f"utility).  Pick a code from the official list — e.g. " +
        ", ".join(f"{c} ({catalog[c]})" for c in list(catalog)[:3]) +
        " — see GET /api/salary/catalog → business_codes.")



