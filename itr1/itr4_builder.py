def build_itr4(data: dict, *, creation_info: dict | None = None) -> dict:
    """Build the official ITR-4 JSON plus the computation report."""
    reset_scopes()
    data = copy.deepcopy(data or {})
    warnings: list[str] = []

    personal = data.get("personal", {}) or {}
    filing = data.get("filing", {}) or {}
    opt_out = bool(filing.get("opt_out_new_regime"))
    dob = _s(personal, "dob") or "1990-01-01"

    # Residential status / assessee-status gating, mirroring the official
    # utility macros:
    #  * ITR-4 Sheet1 Worksheet_Change: when ResidentialStatus1 starts with
    #    "NR" (non-resident) the utility runs Lock44AD — locking and CLEARING
    #    the 44AD cells (BP_E1a/E1b/E2a/E2b) and the 44ADA cells
    #    (BP_E3_GR, BP_E4_PI44ADA).  RNOR ("NOR…") is NOT locked: an RNOR is
    #    resident u/s 6 and keeps the presumptive sections.
    #  * Portal validation rule 212: "HUF is not eligible to claim
    #    presumptive income u/s 44ADA."
    residential_status = (_s(personal, "residential_status")
                          or _s(filing, "residential_status") or "RES").upper()[:3]
    status = (_s(personal, "status") or "I").upper()[:1]

    pres = compute_presumptive(data)
    warnings.extend(pres["warnings"])

    if residential_status == "NRI":
        if pres["44ad_rows"] or pres["44ada_rows"]:
            raise DataError(
                "residential status is Non-Resident: presumptive income "
                "u/s 44AD / 44ADA is not available to a non-resident — the "
                "official ITR-4 utility locks and clears those cells for "
                "'NR' (sections 44AD(1)/44ADA(1) apply only to a resident "
                "assessee).  File ITR-3 instead.")
        if pres["44ae_rows"]:
            warnings.append(
                "Residential status is Non-Resident: ITR-4 is meant for "
                "resident assessees (the utility only warns for NR goods-"
                "carriage filers — 'returns for income of non-residents are "
                "required to be filed in ITR 3/5'); consider ITR-3.")
    if status == "H" and pres["44ada_rows"]:
        raise DataError(
            "HUF is not eligible to claim presumptive income u/s 44ADA "
            "(ITR-4 validation rule 212) — remove the 44ADA rows or file "
            "the applicable form.")

    salary_block, hra_block = _build_salary(data, opt_out, warnings)
    exp = data.get("_salary_expansion")
    hp_blocks, hp_total = _build_house_property(data.get("house_properties"),
                                                opt_out, warnings)
    others_block, oth_src_total, ded_57iia = _build_other_sources(
        data.get("other_sources"), opt_out, warnings)
    _build_exempt_income(data.get("exempt_income"), warnings)

    if opt_out and hra_block:
        data["_hra_block"] = hra_block

    # legacy single-line 112A box (same as ITR-1; gain > 1.25 lakh → ITR-2)
    l_in = data.get("ltcg112a") or {}
    with field_scope("LTCG u/s 112A", "ltcg112a"):
        ltcg = max(0, _g(l_in, "sale_consideration") - _g(l_in, "cost_of_acquisition"))
        if ltcg > C.MAX_LTCG_112A:
            warnings.append("LTCG u/s 112A above Rs. 1.25 lakh cannot be reported in "
                            "ITR-4; use ITR-2 (rule 217).")
        ltcg = min(ltcg, C.MAX_LTCG_112A)
    ltcg_for_gti = ltcg

    salary_171 = salary_block["Salary"]
    with field_scope("Income from other sources", "other_sources"):
        interest_income = sum(_g(r, "amount") for r in (data.get("other_sources") or [])
                              if _s(r, "nature") in ("SAV", "IFD", "TAX"))
        savings_interest = sum(_g(r, "amount") for r in (data.get("other_sources") or [])
                               if _s(r, "nature") == "SAV")

    gti_excl_ltcg = (pres["total_income"] + salary_block["IncomeFromSal"]
                     + hp_total + oth_src_total)
    gti_incl_ltcg = gti_excl_ltcg + ltcg_for_gti

    usr_via, elig_via, ded_scheds, via_total = _build_vi_a(
        data, opt_out, gti_excl_ltcg, salary_171,
        _s(personal, "employer_category", "NA"), dob,
        interest_income, savings_interest, ded_57iia > 0, warnings)

    total_income = T.round_off_income(max(0, gti_incl_ltcg - via_total))
    with field_scope("Total income", "presumptive"):
        if total_income > TURNOVER_CAP_ITR4:
            warnings.append(f"Total income Rs. {total_income:,} exceeds the Rs. 50,00,000 "
                            "ceiling for ITR-4 — use ITR-3 instead.")

    tds_sched, tds_total, tcs_total = _itr4_tax_schedules(data)
    filing_date = _s(filing, "filing_date") or str(TODAY())
    return_section = _g(filing, "return_section", 11)
    with field_scope("Relief u/s 89", "relief_89"):
        section89 = _g(data, "relief_89")
    if exp and exp.get("arrears_rows") and not section89:
        dob_year = int(dob[:4]) if dob[:4].isdigit() else None
        w10e = SX.relief_89_working(total_income, exp["arrears_rows"],
                                    regime="old" if opt_out else "new", dob_year=dob_year)
        data["_form10e"] = w10e
        section89 = w10e["relief89"]
        if section89 > 0:
            warnings.append(f"Relief u/s 89 (Form 10E): Rs. {section89:,} computed "
                            "automatically from arrear details.")
    tax = T.compute_tax(total_income=total_income, opt_out_new_regime=opt_out, dob=dob,
                        residential_status=residential_status, status=status,
                        section89=section89, filing_date=filing_date,
                        return_section=return_section, tds=tds_total, tcs=tcs_total,
                        advance_tax_challans=(data.get("tax_paid") or {}).get("challans"),
                        ltcg112a=ltcg,
                        interest_override=data.get("interest_override"))

    # ---------------- document ----------------
    usr_props = _USR_VIA_PROPS
    elig_props = _ELIG_VIA_PROPS
    inc_ded = {
        "IncomeFromBusinessProf": pres["total_income"],
        "GrossSalary": salary_block["GrossSalary"],
        "Salary": salary_block["Salary"],
        "PerquisitesValue": salary_block["PerquisitesValue"],
        "ProfitsInSalary": salary_block["ProfitsInSalary"],
        "AllwncExemptUs10": salary_block["AllwncExemptUs10"],
        "NetSalary": salary_block["NetSalary"],
        "DeductionUs16": salary_block["DeductionUs16"],
        "DeductionUs16ia": salary_block["DeductionUs16ia"],
        "EntertainmntalwncUs16ii": salary_block["EntertainmentAlw16ii"],
        "ProfessionalTaxUs16iii": salary_block["ProfessionalTaxUs16iii"],
        "IncomeFromSal": salary_block["IncomeFromSal"],
        "TotalIncomeChargeableUnHP": hp_total,
        "IncomeOthSrc": oth_src_total + ded_57iia,
        "OthersInc": others_block,
        "DeductionUs57iia": ded_57iia,
        "GrossTotIncome": gti_excl_ltcg,
        "GrossTotIncomeIncLTCG112A": gti_incl_ltcg,
        "UsrDeductUndChapVIA": {k: v for k, v in usr_via.items() if k in usr_props},
        "DeductUndChapVIA": {k: v for k, v in elig_via.items() if k in elig_props},
        "TotalIncome": total_income,
    }
    if hp_blocks:
        inc_ded["PropertyDetails"] = hp_blocks

    tax_comp = {
        "TotalTaxPayable": tax["TotalTaxPayable"],
        "Rebate87A": tax["Rebate87A"],
        "TaxPayableOnRebate": tax["TaxPayableOnRebate"],
        "EducationCess": tax["EducationCess"],
        "GrossTaxLiability": tax["GrossTaxLiability"],
        "NetTaxLiability": tax["NetTaxLiability"],
        "IntrstPay": tax["IntrstPay"],
        "TotTaxPlusIntrstPay": tax["TotTaxPlusIntrstPay"],
    }
    if section89:
        tax_comp["Section89"] = section89

    bank_rows = []
    for b in (data.get("bank_accounts") or []):
        bank_rows.append({
            "IFSCCode": _s(b, "ifsc"), "BankName": _s(b, "bank_name"),
            "BankAccountNo": _s(b, "account_no"),
            "AccountType": _s(b, "account_type", "SB"),
            "UseForRefund": "true" if b.get("use_for_refund") else "false",
        })
    if not bank_rows:
        warnings.append("At least one bank account is required for the return.")

    ver = data.get("verification", {}) or {}
    ver_block = {
        "Declaration": {
            "AssesseeVerName": _s(ver, "name"),
            "FatherName": _s(ver, "father_name") or _s(personal, "father_name"),
            "AssesseeVerPAN": _s(ver, "pan") or _s(personal, "pan"),
        },
        "Capacity": _s(ver, "capacity", "S"),
        "Place": _s(ver, "place"),
    }

    itr4 = {
        "CreationInfo": _creation_block(creation_info),
        "Form_ITR4": {
            "FormName": "ITR-4",
            # Official utility wording, verbatim (incl. its original spelling).
            "Description": UTILITY_FORM_DESCRIPTION["ITR4"],
            "AssessmentYear": "2026", "SchemaVer": "Ver1.0", "FormVer": "Ver1.0",
        },
        "PersonalInfo": _personal_info(data),
        "FilingStatus": _filing_status_itr4(data, warnings),
        "IncomeDeductions": inc_ded,
        "TaxComputation": tax_comp,
        "TaxPaid": {"TaxesPaid": tax["TaxesPaid"],
                    "BalTaxPayable": tax["BalTaxPayable"]},
        "Refund": {"RefundDue": tax["RefundDue"],
                   "BankAccountDtls": {"AddtnlBankDetails": bank_rows}},
        "Verification": ver_block,
    }
    if data.get("_hra_block"):
        itr4["ScheduleEA10_13A"] = data["_hra_block"]
    if ltcg > 0:
        itr4["LTCG112A"] = {
            "TotSaleCnsdrn": _g(l_in, "sale_consideration"),
            "TotCstAcqisn": _g(l_in, "cost_of_acquisition"),
            "LongCap112A": ltcg,
        }
    bp = _schedule_bp(pres)
    if bp:
        itr4["ScheduleBP"] = bp
    for key, value in ded_scheds.items():
        if key in _ITR4_PROPS:
            itr4[key] = value
    for key, block in tds_sched.items():
        row_key = {"TDSonSalaries": "TDSonSalary",
                   "TDSonOthThanSals": "TDSonOthThanSalDtls",
                   "ScheduleTDS3Dtls": "TDS3Details",
                   "ScheduleTCS": "TCS",
                   "ScheduleIT": "TaxPayment"}[key]
        if not block[row_key]:       # every detail array is minItems: 1
            continue
        itr4[key] = block

    doc = {"ITR": {"ITR4": itr4}}
    report = {
        "form": "ITR4", "regime": "old" if opt_out else "new",
        "presumptive": pres,
        "business_income": pres["total_income"],
        "salary_income": salary_block["IncomeFromSal"], "hp_income": hp_total,
        "other_sources_income": oth_src_total,
        "gross_total_income_excl_ltcg": gti_excl_ltcg,
        "gross_total_income_incl_ltcg": gti_incl_ltcg,
        "ltcg112a": ltcg, "total_income": total_income,
        "deductions_eligible": elig_via, "tax": tax, "warnings": warnings,
        "salary_expansion": exp, "form10e": data.get("_form10e"),
    }
    return {"json": doc, "report": report}
