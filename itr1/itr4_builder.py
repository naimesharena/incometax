def _resolve(node):
    while isinstance(node, dict) and "$ref" in node:
        node = D4[node["$ref"].split("/")[-1]]
    return node if isinstance(node, dict) else {}


_ITR4_PROPS = set((_resolve(D4["ITR"]["properties"]["ITR4"]).get("properties") or {}))
