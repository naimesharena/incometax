def _itr4_tax_schedules(data):
    tp = data.get("tax_paid") or {}
    tds1_rows = []
    for r in (tp.get("tds_on_salary") or []):
        with field_scope("TDS on salary", "tax_paid.tds_on_salary"):
            tds = _g(r, "tds")
        if tds <= 0:
            continue
        tds1_rows.append({
            "EmployerOrDeductorOrCollectDetl": {
                "TAN": _s(r, "tan"),
                "EmployerOrDeductorOrCollecterName": _s(r, "employer_name")},
            "IncChrgSal": _g(r, "salary_income"),
            "TotalTDSSal": tds,
        })
    tds2_rows = []
    for r in (tp.get("tds_others") or []):
        with field_scope("TDS other than salary", "tax_paid.tds_others"):
            claimed = min(_g(r, "tds_claimed"), _g(r, "tds_deducted"))
        if claimed <= 0:
            continue
        tds2_rows.append({
            "TANOfDeductor": _s(r, "tan"),
            "TDSDeducted": _g(r, "tds_deducted"),
            "TDSSection": _s(r, "section", "94A"),
            "TDSClaimed": claimed,
            "GrossAmount": _g(r, "amount_paid"),
            "HeadOfIncome": _s(r, "head_of_income") or "OS",
            "TDSCreditCarriedFwd": 0,
        })
    tds3_rows = []
    for r in (tp.get("tds3") or []):
        with field_scope("TDS on rent", "tax_paid.tds3"):
            claimed = min(_g(r, "tds_claimed"), _g(r, "tds_deducted"))
        if claimed <= 0:
            continue
        row = {
            "PANofTenant": _s(r, "tenant_pan"),
            "TDSDeducted": _g(r, "tds_deducted"),
            "TDSSection": _s(r, "section", "4-IB"),
            "TDSClaimed": claimed,
            "GrossAmount": _g(r, "gross_receipt"),
            "HeadOfIncome": _s(r, "head_of_income") or "HP",
            "TDSCreditCarriedFwd": 0,
        }
        if _s(r, "tenant_aadhaar"):
            row["AadhaarofTenant"] = _s(r, "tenant_aadhaar")
        tds3_rows.append(row)
    tcs_rows = []
    for r in (tp.get("tcs") or []):
        with field_scope("TCS", "tax_paid.tcs"):
            claimed = min(_g(r, "tcs_claimed"), _g(r, "tcs_collected"))
        if claimed <= 0:
            continue
        tcs_rows.append({
            "EmployerOrDeductorOrCollectDetl": {
                "TAN": _s(r, "tan"),
                "EmployerOrDeductorOrCollecterName": _s(r, "collector_name")},
            "Amtfrom26AS": _g(r, "tcs_collected"),
            "TotalTCS": _g(r, "tcs_collected"),
            "AmtTCSClaimedThisYear": claimed,
        })
    challans = []
    for c in (tp.get("challans") or []):
        with field_scope("Advance/SAT challan", "tax_paid.challans"):
            if _g(c, "amount") <= 0:
                continue
            challans.append({"BSRCode": _s(c, "bsr_code"), "DateDep": _s(c, "date"),
                             "SrlNoOfChaln": _g(c, "challan_no"), "Amt": _g(c, "amount")})
    out = {
        "TDSonSalaries": {"TDSonSalary": tds1_rows,
                          "TotalTDSonSalaries": sum(r["TotalTDSSal"] for r in tds1_rows)},
        "TDSonOthThanSals": {"TDSonOthThanSalDtls": tds2_rows,
                             "TotalTDSonOthThanSals": sum(r["TDSClaimed"] for r in tds2_rows)},
        "ScheduleTDS3Dtls": {"TDS3Details": tds3_rows,
                             "TotalTDS3Details": sum(r["TDSClaimed"] for r in tds3_rows)},
        "ScheduleTCS": {"TCS": tcs_rows,
                        "TotalSchTCS": sum(r["AmtTCSClaimedThisYear"] for r in tcs_rows)},
        "ScheduleIT": {"TaxPayment": challans,
                       "TotalTaxPayments": sum(c["Amt"] for c in challans)},
    }
    tds_total = (out["TDSonSalaries"]["TotalTDSonSalaries"]
                 + out["TDSonOthThanSals"]["TotalTDSonOthThanSals"]
                 + out["ScheduleTDS3Dtls"]["TotalTDS3Details"])
    return out, tds_total, out["ScheduleTCS"]["TotalSchTCS"]


